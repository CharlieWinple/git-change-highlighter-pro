'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { GitReader } = require('../src/git');
const { compute } = require('../src/diff');
test('real Git: staged + unstaged, unstage, commit, rename, Unicode paths and read-only guarantees', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'gch-test-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', windowsHide: true });
  git('init'); git('config', 'user.email', 'test@example.invalid'); git('config', 'user.name', 'Test'); git('config', 'core.autocrlf', 'false');
  const reader = new GitReader(), file = path.join(root, '测试 file.py');
  await fs.writeFile(file, 'a\nb\n');
  assert.equal((await reader.read(root, file)).base, '');
  git('add', '.'); git('commit', '-m', 'baseline');
  await fs.writeFile(file, 'a changed\nb\n'); git('add', '.');
  await fs.writeFile(file, 'a changed\nb\nextra\n');
  const beforeStatus = git('status', '--porcelain=v1'), beforeIndex = await fs.readFile(path.join(root, '.git/index'));
  let snapshot = await reader.read(root, file);
  assert.equal(snapshot.base, 'a\nb\n');
  let result = compute(snapshot.base, await fs.readFile(file, 'utf8'));
  assert.deepEqual(result.hunks.flatMap(h => h.modified), [0]); assert.deepEqual(result.hunks.flatMap(h => h.added), [2]);
  assert.equal(git('status', '--porcelain=v1'), beforeStatus); assert.deepEqual(await fs.readFile(path.join(root, '.git/index')), beforeIndex);
  git('reset', 'HEAD', '--', '测试 file.py');
  assert.equal((await reader.read(root, file)).base, snapshot.base);
  git('add', '.'); git('commit', '-m', 'changes');
  snapshot = await reader.read(root, file);
  assert.equal(compute(snapshot.base, await fs.readFile(file, 'utf8')).hunks.length, 0);
  git('mv', '测试 file.py', 'renamed.py');
  const renamed = path.join(root, 'renamed.py');
  assert.equal((await reader.read(root, renamed)).base, snapshot.base);
  await fs.appendFile(renamed, 'new line\n');
  assert.deepEqual(compute((await reader.read(root, renamed)).base, await fs.readFile(renamed, 'utf8')).hunks.flatMap(h => h.added), [3]);
  const untracked = path.join(root, 'new.tex'); await fs.writeFile(untracked, 'hello\n');
  assert.equal((await reader.read(root, untracked)).base, '');
  const empty = path.join(root, 'empty.m'); await fs.writeFile(empty, '');
  assert.equal(compute((await reader.read(root, empty)).base, '').hunks.length, 0);
});
